#!/usr/bin/env node
/**
 * Generate ccv1OthersEntries.ts from ccv1-top-holders-to-add.json.
 * Run after: node scripts/find-ccv1-top-holders.mjs
 */
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const data = JSON.parse(readFileSync(join(__dirname, 'ccv1-top-holders-to-add.json'), 'utf8'));
const entries = data.map((e) => ({
  username: '',
  displayName: e.displayName,
  classification: e.classification,
  publicKeyBase58Check: e.publicKeyBase58Check,
}));
const outPath = join(__dirname, '..', 'src', 'data', 'ccv1OthersEntries.ts');
const content = `/**
 * Top 10 CC holders of top 1000 CC coins – reduces Others-Unaccounted CCv1.
 * Auto-generated by: node scripts/gen-ccv1-wallet-entries.mjs
 * Source: scripts/ccv1-top-holders-to-add.json (from find-ccv1-top-holders.mjs)
 */
import type { WalletConfig } from '@/api/walletApi';

export const CCV1_OTHERS_ENTRIES: WalletConfig[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(outPath, content);
console.log('Wrote', entries.length, 'entries to', outPath);
